#!/usr/bin/env python3
"""
static_site_generator.py - Manual build step for michael.nekoweb.org

Run this BEFORE `git push` (the github workflow deploys public/ as-is):

    python3 static_site_generator.py

What it does
------------
* Converts the markdown in content/ into HTML: every content/**/*.md
  becomes public/**/*.html (same relative path), and each folder with
  articles gets a landing page public/<folder>.html listing them, so the
  sections appear in the sidebar like technical.html does. Pages that
  carry the "Generated by static_site_generator.py" marker are regenerated from the
  markdown on every run; hand-written pages in public/ are never touched,
  and generated pages whose markdown has been deleted are pruned.
* Scans every *.html file under public/, including subfolders, so the
  git structure and the webpage structure stay in sync.
* Builds a hierarchical sitemap from the folder structure. A page named
  <section>.html is treated as the landing page for the sibling folder
  <section>/, so pages inside technical/ are shown as children of
  technical.html, e.g.:

      Home (index.html)
      Cool stuff! (cool_stuff.html)
      Technical landing page (technical.html)
        Codecs (technical/codecs.html)

* Excludes special folders from the sitemap:
  - assets/  - assets only (images, music), never webpages
  - unlisted/ - secret pages you reach by typing the URL or exploring the
                site; they still get the sidebar, just no link to them.
  The 404 page (not_found.html) is also left out of the sitemap.
* Injects a fixed left-hand sidebar into every page (except inside assets/).
  The sidebar shows a compact music player (the Tamatown funky loop, native
  audio controls, never autoplays) above the sitemap, plus the sitemap, a
  sticker linking to nekoweb.org and a copyright notice. The page or section
  you are currently on is highlighted. Branches only expand when relevant:
  the home page shows just the top-level pages, and a section's second- and
  third-level pages appear once you are on that section or on a page inside
  it, so the sidebar stays compact as the site grows. Links are written
  relative to each page's own folder, so pages in subfolders get
  "../index.html" and so on.
  On phones (max-width 600px) the sidebar turns into a full-width top bar
  so the content gets the whole viewport.
* Wraps the body text of every page in a <main class="content-box"> element
  so the text sits on a cream panel centered in the viewport, with the
  background pattern visible all around it (styled in public/style.css).
  A page containing <!-- nocontentbox --> opts out of that wrapper so
  hand-crafted pages can control their own layout; the marker is honored in
  both directions (adding it unwraps, removing it re-wraps), and removing
  the marker converges back to the normal box. Like the sidebar, this is
  idempotent: re-running the build re-wraps the current box instead of
  nesting another one.

The script is idempotent: re-running it replaces any previously injected
sidebar instead of duplicating it, so it is safe to run after every edit.
If you add, rename or remove a page, just run the build again.

The injected markup is pure HTML + CSS. No JavaScript is used anywhere.
"""

