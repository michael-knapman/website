@dataclass
class PageNode:
    """A clickable page in the sitemap."""

    rel_path: str  # posix path relative to PUBLIC, e.g. "technical/codecs.html"
    label: str
    children: list = field(default_factory=list)


@dataclass
class GroupNode:
    """A non-clickable section heading, used when a folder has no landing page."""

    label: str
    children: list = field(default_factory=list)


def escape_html(text):
    """Escape text so it is safe inside HTML markup and attributes."""
    return htmlmod.escape(text, quote=True)


def extract_title(html, filename):
    match = re.search(r"<title[^>]*>([^<]*)</title>", html, re.IGNORECASE)
    if match and match.group(1).strip():
        # Titles in <title> tags carry HTML entities; unescape so callers
        # can apply exactly one round of escaping for their own context.
        return htmlmod.unescape(match.group(1).strip())
    return filename.removesuffix(".html")


def parent_dir(rel_path):
    """Parent directory of a posix rel path, "" for the root folder."""
    return posixpath.dirname(rel_path)


def stem(rel_path):
    """File stem, e.g. "technical/codecs.html" -> "codecs"."""
    return posixpath.splitext(posixpath.basename(rel_path))[0]


def rel_href(cur_dir, target_rel_path):
    """Relative href from a page in cur_dir to a sitemap target."""
    if not cur_dir:
        return target_rel_path
    up = "../" * len(cur_dir.split("/"))
    return up + target_rel_path


class Sitemap:
    """Builds and holds the hierarchical sitemap for the whole site."""

    def __init__(self):
        self.pages = {}       # rel_path -> PageNode
        self.pages_in_dir = {}  # dir -> [rel_path, ...]
        self.all_dirs = set()   # every directory that contains a page below it

        self._scan_pages()
        self._index_dirs()
        self.root = self._build_tree("")

    def _is_excluded(self, rel_path):
        parts = rel_path.split("/")[:-1]
        return any(part in EXCLUDE_FROM_SITEMAP for part in parts)

    def _scan_pages(self):
        for path in sorted(PUBLIC.rglob("*.html")):
            rel = path.relative_to(PUBLIC).as_posix()
            if self._is_excluded(rel):
                continue
            if path.name == NOT_FOUND_FILE:
                continue
            label = (HOME_LABEL if rel == HOMEPAGE_FILE
                     else extract_title(path.read_text(encoding="utf-8"), path.name))
            self.pages[rel] = PageNode(rel, label)

    def _index_dirs(self):
        for rel in self.pages:
            d = parent_dir(rel)
            self.pages_in_dir.setdefault(d, []).append(rel)
            self.all_dirs.add(d)  # when rel's parent == "" we add "" directly
            while d:
                d = parent_dir(d)
                self.all_dirs.add(d)

    def _child_dirs_with_pages(self, cur_dir):
        """Immediate sub-folders of cur_dir that contain pages somewhere below."""
        found = set()
        prefix = f"{cur_dir}/" if cur_dir else ""
        for rel in self.pages:
            if rel.startswith(prefix):
                rest = rel[len(prefix):]
                if "/" in rest:
                    found.add(rest.split("/", 1)[0])
        return found

    def _build_tree(self, cur_dir):
        children = []
        my_pages = self.pages_in_dir.get(cur_dir, [])
        my_pages = sorted(my_pages, key=lambda rel: (rel != HOMEPAGE_FILE, stem(rel)))
        for rel in my_pages:
            node = self.pages[rel]
            section = stem(rel) if not cur_dir else posixpath.join(cur_dir, stem(rel))
            if section in self.all_dirs:
                node.children = self._build_tree(section)
            children.append(node)

        for sub in sorted(self._child_dirs_with_pages(cur_dir)):
            section = sub if not cur_dir else posixpath.join(cur_dir, sub)
            landing = f"{sub}.html" if not cur_dir else posixpath.join(cur_dir, sub + ".html")
            if landing not in self.pages:
                group = GroupNode(sub)
                group.children = self._build_tree(section)
                children.append(group)
        return children


def strip_block(text, start_token, end_token):
    """Remove a previously injected block (idempotency).

    The blocks this script writes own the single newline on each side, so
    both are consumed here and re-added on injection. Without that, blank
    lines would creep into the file on every run.
    """
    pattern = re.compile(
        r"\n?<!--\s*" + re.escape(start_token) + r"\s*-->.*?"
        r"<!--\s*" + re.escape(end_token) + r"\s*-->\n?",
        re.DOTALL,
    )
    return pattern.sub("", text)


def normalize_marker_spacing(html):
    """Normalize blank lines next to the injected blocks.

    Guarantees deterministic spacing at the block boundaries (the CSS marker
    sits on its own line, one blank line separates the sidebar footer from
    the page content) and cleans up blank-line runs left over from older
    static_site_generator versions. This is idempotent: on already-clean files it is a
    no-op.
    """
    # CSS block: exactly one newline before the opening marker. \s* (not
    # just \n*) so leftover indentation can never pile up extra newlines.
    html = re.sub(r"\s*(<!--\s*BEGINSIDEBAR:CSS\s*-->)", r"\n\1", html)
    # Sidebar block: exactly one blank line after the closing marker.
    html = re.sub(
        r"(<!--\s*ENDSIDEBAR\s*-->)(\n*)", r"\1\n\n", html
    )
    return html


CONTENT_BOX_OPEN = '<main class="content-box">'
CONTENT_BOX_CLOSE = "</main>"

# A page containing <!-- nocontentbox --> opts out of the central cream text
# box so it can control its own layout (e.g. a hand-crafted art shrine). The
# sidebar and stylesheet are still injected; only the wrapper is skipped.
NO_CONTENTBOX_MARKER = "nocontentbox"


def strip_content_box(content):
    """Remove a <main class="content-box">...</main> wrapper, if present.

    The wrapper can sit anywhere in the content region (a page may carry the
    opt-out marker or other comments before it). Returns the inner text with
    wrapper edges dropped; returns `content` unchanged when no wrapper found.
    """
    open_pos = content.find(CONTENT_BOX_OPEN)
    close_pos = content.rfind(CONTENT_BOX_CLOSE)
    if open_pos == -1 or close_pos == -1 or close_pos < open_pos:
        return content
    inner = content[open_pos + len(CONTENT_BOX_OPEN):close_pos].strip("\n")
    prefix = content[:open_pos].rstrip("\n")
    suffix = content[close_pos + len(CONTENT_BOX_CLOSE):].lstrip("\n")
    return (prefix + "\n" + inner + "\n" + suffix).strip("\n")


def wrap_content(html):
    """Wrap the page's body text in the central cream text box.

    Everything between the sidebar's closing marker and </body> becomes the
    inside of a <main class="content-box"> element. style.css centers the
    box and gives it its cream background, leaving the pattern visible on
    all four sides.

    Idempotent: a page that already carries the wrapper is left alone, so
    re-running the build never nests a second box. Pages that ask to opt out
    with <!-- nocontentbox --> are *unwrapped* instead, so toggling the
    marker in either direction always converges on the page being in the
    right state.
    """
    body_close = html.rfind("</body>")
    if body_close == -1:
        return html

    marker = f"<!-- {SIDEBAR_MARKER_END} -->"
    marker_end = html.rfind(marker)
    if marker_end == -1 or marker_end > body_close:
        return html

    content = html[marker_end + len(marker):body_close]

    if f"<!-- {NO_CONTENTBOX_MARKER} -->" in html:
        unwrapped = strip_content_box(content)
        if unwrapped is not content:
            return (html[:marker_end + len(marker)] + "\n"
                    + unwrapped + "\n" + html[body_close:])
        return html  # already unwrapped

    if CONTENT_BOX_OPEN in content:
        return html  # already wrapped

    wrapper = (
        f"\n{CONTENT_BOX_OPEN}\n"
        + content.strip("\n")
        + f"\n{CONTENT_BOX_CLOSE}\n"
    )
    return html[:marker_end + len(marker)] + wrapper + html[body_close:]


def is_node_active(node, current_rel):
    """True when the current page is this node or one of its descendants.

    This is what decides whether a branch is expanded in the sidebar: a
    section's sub-pages appear when you are on the section itself (its
    landing page) or on any page inside it, and stay hidden otherwise so
    the sidebar does not balloon on large sites.
    """
    if isinstance(node, PageNode):
        if current_rel == node.rel_path:
            return True
        section = posixpath.splitext(node.rel_path)[0]  # "technical.html" -> "technical"
    else:  # GroupNode: the branch is the folder with this label
        section = node.label
    return current_rel.startswith(section + "/")


def render_nav(nodes, cur_dir, current_rel, depth=0):
    """Render the nested <ul> sitemap. Handles page and group nodes.

    A branch is only expanded when is_node_active is true, i.e. the visitor
    is on that branch: the home page shows just the top level, and second/
    third-level pages appear once you are on the relevant section (or on a
    page inside it). Sub-pages are never a dead end, because every folder
    has a landing page that links to them.
    """
    out = []
    pad = "    " * (depth + 2)
    for node in nodes:
        if isinstance(node, PageNode):
            href = rel_href(cur_dir, node.rel_path)
            is_current = node.rel_path == current_rel
            extra = ' class="current" aria-current="page"' if is_current else ""
            link = (f"{pad}<li><a href=\"{href}\"{extra}>"
                    f"{escape_html(node.label)}</a>")
            if node.children and is_node_active(node, current_rel):
                # The child <ul> nests *inside* the <li> (a bare <ul> under
                # <ul> is invalid HTML and hurts screen readers).
                out.append(link)
                out.append(f"{pad}<ul>")
                out.extend(render_nav(node.children, cur_dir, current_rel, depth + 1))
                out.append(f"{pad}</ul></li>")
            else:
                out.append(link + "</li>")
        else:  # GroupNode
            head = (f"{pad}<li class=\"group\"><span>"
                    f"{escape_html(node.label)}</span>")
            if node.children and is_node_active(node, current_rel):
                out.append(head)
                out.append(f"{pad}<ul>")
                out.extend(render_nav(node.children, cur_dir, current_rel, depth + 1))
                out.append(f"{pad}</ul></li>")
            else:
                out.append(head + "</li>")
    return out


def build_sidebar(sitemap, current_rel):
    cur_dir = parent_dir(current_rel)
    nav_lines = render_nav(sitemap.root, cur_dir, current_rel)
    nav = "\n".join(nav_lines)
    linkedin = (
        f'<a href="{LINKEDIN_URL}">'
        f'<img src="{rel_href(cur_dir, LINKEDIN_IMG)}" '
        f'width="64" height="54" alt="LinkedIn">'
        "</a>"
    )
    return (
        f"\n<!-- {SIDEBAR_MARKER_START} -->\n"
        f'<aside class="sidebar">\n'
        + AUDIO_PLAYER.format(src=rel_href(cur_dir, MUSIC_FILE))
        + f"    <nav class=\"sidebar-nav\" aria-label=\"Sitemap\">\n"
        f"        <ul>\n"
        f"{nav}\n"
        f"        </ul>\n"
        f"    </nav>\n"
        f"    <div class=\"sidebar-foot\">\n"
        f"        {STICKER}\n"
        f"        {linkedin}\n"
        f"        <p>{escape_html(COPYRIGHT)}</p>\n"
        f"    </div>\n"
        f"</aside>\n"
        f"<!-- {SIDEBAR_MARKER_END} -->\n"
    )


def build_css_block(cur_dir):
    """The injected head block: favicon + inline site CSS + sidebar CSS.

    style.css is inlined rather than <link>ed because it is tiny: inlining
    removes a render-blocking network request (a PageSpeed recommendation).
    The inlined copy lives inside the page, so url(assets/...) references in
    it would resolve relative to the page's folder; they are rewritten to
    root-absolute /assets/... paths, which work from any page depth. The
    favicon link (also injected here) stops browsers from 404-ing on the
    default /favicon.ico request.
    """
    site_css = (PUBLIC / "style.css").read_text(encoding="utf-8")
    site_css = re.sub(r"url\(\s*assets/", "url(/assets/", site_css)
    return (
        f"<!-- {CSS_MARKER_START} -->\n"
        f'<link rel="icon" href="/favicon.ico">\n'
        f"<style id=\"site-css\">{site_css}</style>\n"
        f"<style id=\"sidebar-css\">{SIDEBAR_CSS}</style>\n"
        f"<!-- {CSS_MARKER_END} -->\n"
    )


