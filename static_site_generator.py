def escape_attr(text):
    """Escape text so it is safe inside a double-quoted HTML attribute."""
    return escape_html(text)


def auto_description(html, rel_path):
    """Build a meta description from the page's own first real paragraph.

    Only looks at the body text (never the injected sidebar), skips filler
    paragraphs shorter than 15 chars, and prefixes the page title.
    """
    title = extract_title(html, posixpath.basename(rel_path))
    # Never describe the page from the injected sidebar/audio blocks.
    body = strip_block(html, SIDEBAR_MARKER_START, SIDEBAR_MARKER_END)
    match = re.search(r"<main[^>]*>(.*?)</main>", body, re.DOTALL)
    if match:
        body = match.group(1)
    for para in re.findall(r"<p[^>]*>(.*?)</p>", body, re.DOTALL):
        text = re.sub(r"<[^>]+>", " ", para)
        text = htmlmod.unescape(text)
        # Sweep up any tag-like leftovers revealed by unescaping.
        text = re.sub(r"<[^>]*>", " ", text)
        text = re.sub(r"\s+", " ", text).strip()
        if len(text) >= 15:
            snippet = f"{title} - {text}" if title else text
            if len(snippet) > DESCRIPTION_MAX:
                snippet = snippet[: DESCRIPTION_MAX - 1].rstrip() + "…"
            return snippet
    return (title or posixpath.basename(rel_path))[:DESCRIPTION_MAX]


def collapse_head_blanks(html):
    """Collapse runs of blank lines inside <head>, outside <style> blocks.

    Removes the whitespace crumbs that older build versions left behind when
    replacing the meta description, without touching the hand-written CSS
    inside <style>.</style> tags.
    """
    match = re.search(r"<head[^>]*>(.*?)</head>", html, re.IGNORECASE | re.DOTALL)
    if not match:
        return html
    head = match.group(1)
    parts = re.split(r"(<style[^>]*>.*?</style>)", head, re.IGNORECASE | re.DOTALL)
    for i in range(0, len(parts), 2):
        parts[i] = re.sub(r"\n(?:[ \t]*\n)+", "\n\n", parts[i])
    return html[: match.start(1)] + "".join(parts) + html[match.end(1):]


def inject_meta_description(html, current_rel):
    """Replace any existing description meta tag with a generated one.

    Idempotent: every existing description tag is removed first and blank
    line crumbs left behind in the head are collapsed, then a single fresh
    tag is inserted after <title>.
    """
    # The old tag owns its whole line (newline + indentation), so removing
    # just the tag cannot leave whitespace crumbs that later passes would
    # treat as content and pad with more newlines.
    html = re.sub(r"\n?[ \t]*" + META_DESC_RE.pattern, "", html)
    html = collapse_head_blanks(html)
    description = PAGE_DESCRIPTIONS.get(
        current_rel, auto_description(html, current_rel)
    )
    meta = f'<meta name="description" content="{escape_attr(description)}">\n'
    match = re.search(r"</title>", html, re.IGNORECASE)
    if match:
        html = html[: match.end()] + "\n    " + meta + html[match.end():]
    elif "</head>" in html:
        html = html.replace("</head>", meta + "</head>", 1)
    else:
        html = meta + html
    return html


def inject_into_page(html, current_rel, sitemap):
    html = strip_block(html, CSS_MARKER_START, CSS_MARKER_END)
    html = strip_block(html, SIDEBAR_MARKER_START, SIDEBAR_MARKER_END)

    css_block = build_css_block(parent_dir(current_rel))
    if "</head>" in html:
        html = html.replace("</head>", css_block + "</head>", 1)
    else:
        html = css_block + html

    sidebar = build_sidebar(sitemap, current_rel)
    # Insert right after the <body> tag. Anchor it to </head> so the search
    # can never match a literal "<body>" inside inlined CSS or a comment.
    match = re.search(r"</head>\s*<body[^>]*>", html, re.IGNORECASE)
    if match:
        html = html[: match.end()] + sidebar + html[match.end():]
    else:
        match = re.search(r"<body[^>]*>", html, re.IGNORECASE)
        if match:
            html = html[: match.end()] + sidebar + html[match.end():]
        else:
            html = sidebar + html

    # Wrap the body text in the central cream text box (see style.css).
    html = wrap_content(html)

    # Per-page SEO meta description (curated map or auto-generated).
    html = inject_meta_description(html, current_rel)

    return normalize_marker_spacing(html)


# ---------------------------------------------------------------------------
# Markdown -> HTML conversion for content/.
#
# content/ holds the canonical source text of the digital garden as markdown.
# This section converts that tiny Markdown subset into HTML at build time, so
# the site stays plain static HTML + CSS: no JavaScript, no database, nothing
# runs in the browser. The converter is deliberately dependency-free (the
# standard library only) and lossless: every construct in content/ is one of
# these, and anything else is escaped and passed through verbatim, never
# rewritten.
#
# Subset supported (verified against every file in content/):
#   # Heading            -> <h1>
#   paragraphs           -> <p>, trailing double spaces become <br>
#   * bullet items       -> <ul>/<li> (flat, one item per line)
#   | pipe tables        -> <table> with <thead>/<tbody>
#   <https://...>        -> <a href="...">
# ---------------------------------------------------------------------------

AUTOLINK_RE = re.compile(r"<(https?://[^<>\s]+)>")


def inline_html(text):
    """Convert <url> autolinks to anchors and HTML-escape everything else.

    The text segments and the URL are handled separately so that escaping
    never mangles an <a href="..."> we just wrote.
    """
    parts = []
    pos = 0
    for match in AUTOLINK_RE.finditer(text):
        parts.append(escape_html(text[pos:match.start()]))
        url = match.group(1)
        parts.append(f'<a href="{escape_html(url)}">{escape_html(url)}</a>')
        pos = match.end()
    parts.append(escape_html(text[pos:]))
    return "".join(parts)


def split_table_row(line):
    """'| a | b |' -> ['a', 'b'] (whitespace trimmed, edge pipes dropped)."""
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [cell.strip() for cell in line.split("|")]


def is_separator_row(line):
    """True for a markdown table separator row like | --- | --- |."""
    cells = split_table_row(line)
    return bool(cells) and all(re.fullmatch(r":?-+:?", cell) for cell in cells)


def render_paragraph(lines):
    """A paragraph block; lines ending in 2+ spaces become <br> hard breaks.

    A hard break on the very last line of a block is dropped, matching
    Markdown: it would hang into an invisible end of paragraph.

    Each line is escaped/autolinked *before* the <br> is appended, so the
    escaping never turns our own break tag into literal "&lt;br&gt;" text.
    """
    out = []
    for i, line in enumerate(lines):
        hard_break = re.search(r"[ \t]{2,}$", line) is not None
        text = inline_html(line.rstrip())
        if hard_break and i < len(lines) - 1:
            out.append(text + "<br>")
        else:
            out.append(text)
    return " ".join(out)


def render_markdown_block(lines):
    """Render one blank-line-separated block of the source file."""
    first = lines[0].strip()

    # Heading: "# Title"
    if first.startswith("#"):
        return f"<h1>{inline_html(first[1:].strip())}</h1>"

    # Flat bullet list: every line starts with "* ".
    if all(line.startswith("* ") for line in lines):
        items = [f"<li>{inline_html(line[2:].strip())}</li>"
                 for line in lines]
        return "<ul>\n" + "\n".join(items) + "\n</ul>"

    # Pipe table: header row followed by a | --- | separator row.
    if (first.startswith("|") and len(lines) >= 2
            and is_separator_row(lines[1])):
        header = "".join(f"<th>{inline_html(c)}</th>"
                         for c in split_table_row(lines[0]))
        body_rows = []
        for line in lines[2:]:
            if not line.strip():
                continue
            cells = "".join(f"<td>{inline_html(c)}</td>"
                            for c in split_table_row(line))
            body_rows.append(f"<tr>{cells}</tr>")
        tbody = "\n".join(body_rows)
        return (f"<table>\n<thead><tr>{header}</tr></thead>\n"
                f"<tbody>\n{tbody}\n</tbody>\n</table>")

    # Plain paragraph (with hard breaks). render_paragraph already escapes
    # each line, so it must not pass through inline_html a second time.
    return f"<p>{render_paragraph(lines)}</p>"


def convert_markdown_to_html(md_text):
    """Convert one content file. Returns (title, body_html).

    The title comes from the first # heading; it also becomes the <title>
    and therefore the sidebar label for this page.
    """
    blocks = []
    current = []
    for line in md_text.splitlines():
        if line.strip():
            current.append(line)
        elif current:
            blocks.append(current)
            current = []
    if current:
        blocks.append(current)

    title = None
    for block in blocks:
        match = re.match(r"#\s+(.+)", block[0].strip())
        if match:
            title = match.group(1).strip()
            break

    body = "\n\n".join(render_markdown_block(block) for block in blocks)
    return title, body


def prettify_section(name):
    """'selected-works' -> 'Selected Works' (for folder landing pages)."""
    return name.replace("-", " ").replace("_", " ").title()


def skeleton_page(title, marker, body_html):
    """A bare page for the sidebar/CSS phase to inject into."""
    return (
        "<!DOCTYPE html>\n"
        '<html lang="en">\n'
        "<head>\n"
        '    <meta charset="UTF-8">\n'
        '    <meta http-equiv="X-UA-Compatible" content="IE=edge">\n'
        '    <meta name="viewport" content="width=device-width, '
        'initial-scale=1.0">\n'
        f"    <title>{escape_html(title)}</title>\n"
        "</head>\n"
        "<body>\n"
        f"<!-- {marker} -->\n"
        f"{body_html}\n"
        "</body>\n"
        "</html>"
    )


def write_generated(path, content, label):
    """Write a generated page; never overwrite a hand-written page."""
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if not GENERATED_RE.search(existing):
            print(f"  skipped {label}: {path} has no generated marker, "
                  "so it is treated as hand-written. Delete it or add the "
                  "marker to let the build own it.")
            return False
        if existing == content:
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def generate_content_pages():
    """Phase 0: convert content/**/*.md into public/**/*.html.

    content/ stays the source of truth: edit the markdown, re-run the build,
    push. Also generates one landing page per folder (public/<folder>.html,
    mirroring technical.html) that lists its articles, and prunes generated
    pages whose markdown no longer exists so the two trees stay in sync.
    """
    if not CONTENT.is_dir():
        print(f"Note: no content folder at {CONTENT}; skipping markdown step.")
        return

    targets = set()    # rel html paths this run wants to exist under public/
    articles = []      # (html_rel, title) for the folder landing pages

    for md in sorted(CONTENT.rglob("*.md")):
        rel = md.relative_to(CONTENT).as_posix()
        html_rel = posixpath.splitext(rel)[0] + ".html"
        title, body = convert_markdown_to_html(
            md.read_text(encoding="utf-8"))
        if not title:
            title = prettify_section(md.stem)
        marker = (f"Generated by static_site_generator.py from content/{rel} - do not "
                  "edit by hand; edit the markdown and re-run static_site_generator.py.")
        targets.add(html_rel)
        articles.append((html_rel, title))
        out = PUBLIC / html_rel
        if write_generated(out, skeleton_page(title, marker, body), html_rel):
            print(f"  generated {html_rel}")

    # One landing page per folder that has articles, listed in the sidebar
    # as a section with its articles as children (like technical.html).
    for folder in sorted(d for d in CONTENT.iterdir() if d.is_dir()):
        section = folder.name
        children = [
            (rel, title) for rel, title in articles
            if rel.startswith(section + "/"
                              ) and "/" not in rel[len(section) + 1:]
        ]
        if not children:
            continue
        section_title = prettify_section(section)
        landing_rel = section + ".html"
        items = "\n".join(
            f'    <li><a href="{rel}">{escape_html(title)}</a></li>'
            for rel, title in sorted(children)
        )
        body = (f"<h1>{escape_html(section_title)}</h1>\n"
                f"<ul>\n{items}\n</ul>")
        marker = (f"Generated by static_site_generator.py from the content/{section}/ "
                  "folder - do not edit by hand; edit the markdown and "
                  "re-run static_site_generator.py.")
        targets.add(landing_rel)
        out = PUBLIC / landing_rel
        if write_generated(out, skeleton_page(section_title, marker, body),
                           landing_rel):
            print(f"  generated {landing_rel}")

    # Prune generated pages whose markdown or folder has been deleted.
    for html in sorted(PUBLIC.rglob("*.html")):
        rel = html.relative_to(PUBLIC).as_posix()
        if rel in targets:
            continue
        if GENERATED_RE.search(html.read_text(encoding="utf-8")):
            html.unlink()
            print(f"  pruned {rel} (source markdown is gone)")


def print_tree(nodes, indent=""):
    for node in nodes:
        if isinstance(node, PageNode):
            print(f"{indent}{node.rel_path}  ({node.label})")
            print_tree(node.children, indent + "  ")
        else:
            print(f"{indent}{node.label}/  (group)")
            print_tree(node.children, indent + "  ")


def main():
    generate_content_pages()
    sitemap = Sitemap()

    html_files = [p for p in sorted(PUBLIC.rglob("*.html"))
                  if not any(part in EXCLUDE_FROM_INJECTION
                             for part in p.relative_to(PUBLIC).parts[:-1])]
    if not html_files:
        print(f"No HTML files found under {PUBLIC}", file=sys.stderr)
        return 1

    print("Build step: sitemap:")
    print_tree(sitemap.root)

    for path in html_files:
        current_rel = path.relative_to(PUBLIC).as_posix()
        html = path.read_text(encoding="utf-8")
        updated = inject_into_page(html, current_rel, sitemap)
        if updated != html:
            path.write_text(updated, encoding="utf-8")
            print(f"  updated {path.name} ({current_rel})")
        else:
            print(f"  unchanged {path.name} ({current_rel})")

    print("Done. You can now git add, git commit, and git push.")
    return 0


